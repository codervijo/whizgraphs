export function Graphic({
  g,
  eager = false,
  caption = true,
  download = false,
  className = "",
}: {
  g: GraphicMeta;
  eager?: boolean;
  caption?: boolean | string;
  download?: boolean;
  className?: string;
}) {
  return (
    <figure className={className}>
      <a href={g.png} className="block overflow-hidden rounded-xl border border-border bg-white shadow-sm" title={`Open full size: ${g.name}`}>
        <img
          src={g.svg}
          alt={g.alt}
          width={g.w}
          height={g.h}
          loading={eager ? "eager" : "lazy"}
          decoding="async"
          fetchPriority={eager ? "high" : "auto"}
          className="h-auto w-full"
        />
      </a>
      {(caption || download) && (
        <figcaption className="mt-2 flex flex-wrap items-baseline justify-between gap-2 text-sm text-muted-foreground">
          {caption && <span>{typeof caption === "string" ? caption : g.caption}</span>}
          {download && (
            <a href={g.png} download className="inline-flex items-center gap-1 font-medium text-primary hover:underline">
              <Download className="h-3.5 w-3.5" /> PNG
            </a>
          )}
        </figcaption>
      )}
    </figure>
  );
}

const FORMAT_ICON: Record<string, typeof FileText> = { PDF: FileText, CSV: Table2, PNG: ImageIcon };

export function DownloadPanel({ title, note, items }: { title: string; note?: string; items: (DownloadMeta & { detail: string })[] }) {
  return (
    <div className="rounded-xl border border-border bg-background p-5 shadow-sm">
      <div className="font-semibold">{title}</div>
      {note && <p className="mt-1 text-sm text-muted-foreground">{note}</p>}
      <ul className="mt-4 space-y-2">
        {items.map((d) => {
          const Icon = FORMAT_ICON[d.format] || Download;
          return (
            <li key={d.href}>
              <a
                href={d.href}
                download
                className="flex items-center gap-3 rounded-lg border border-border px-3 py-2.5 transition-colors hover:border-primary hover:bg-accent/40"
              >
                <span className="grid h-9 w-9 flex-none place-items-center rounded-md bg-accent text-accent-foreground">
                  <Icon className="h-4 w-4" />
                </span>
                <span className="min-w-0 flex-1">
                  <span className="block text-sm font-medium">{d.label}</span>
                  <span className="block text-xs text-muted-foreground">{d.detail}</span>
                </span>
                <span className="rounded bg-muted px-1.5 py-0.5 text-[10px] font-semibold tracking-wide text-muted-foreground">{d.format}</span>
              </a>
            </li>
          );
        })}
      </ul>
    </div>
  );
}

export function EmbedSnippet({ g, pagePath }: { g: GraphicMeta; pagePath: string }) {
  const site = "https://whizgraphs.com";
  const code = `<a href="${site}${pagePath}"><img src="${site}${g.png}" alt="${g.alt.replace(/"/g, "&quot;")}" width="${g.w / 2}" height="${g.h / 2}"></a>\n<p>Infographic by <a href="${site}/">WhizGraphs</a></p>`;
  return (
    <div className="rounded-xl border border-border bg-background p-4">
      <label htmlFor={`embed-${g.id}`} className="text-sm font-semibold">
        Embed this infographic
      </label>
      <textarea
        id={`embed-${g.id}`}
        readOnly
        rows={4}
        defaultValue={code}
        className="mt-2 w-full resize-none rounded-md border border-border bg-muted p-2 font-mono text-xs text-muted-foreground"
      />
    </div>
  );
}

